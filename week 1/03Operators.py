a = 10
b = 3

#Arithmetic
print(a + b)  
print(a - b)  
print(a * b)   
print(a / b)   
print(a // b)  
print(a % b)  
print(a ** b)  

#Comparison
print(5 == 5)  
print(5 != 3)  
print(5 > 3)   
print(5 < 3)   
print(5 >= 5)  
print(5 <= 3)  

#Logical 
x = True
y = False
print(x and y)  
print(x or y)   
print(not x)    

#Assignment
num = 10
num += 5   # same as num = num + 5
print(num)
num -= 3   # num = num - 3
print(num)
num *= 2   # num = num * 2
print(num)
num /= 4   # num = num / 4
print(num)

